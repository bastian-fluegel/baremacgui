"""Build a double-clickable .app bundle around a script.

Pure standard library (plistlib, shutil, subprocess for the icon), so it also imports and is tested
on Linux. The bundle is a thin launcher, not a self-contained app: it starts the Python that built it
(the absolute path of `sys.executable`, a virtual environment included) with the script, so it only
runs on the Mac that built it and stops working when that Python is removed. It is not signed.
"""
from __future__ import annotations

import math
import os
import plistlib
import re
import shlex
import shutil
import stat
import subprocess
import sys
import zlib
import struct

from .errors import BareMacGUIError, PlatformError

_NAME_BAD = re.compile(r'[/:\\\x00-\x1f]')
_IDENTIFIER = re.compile(r"^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$")


def check_app_name(name):
    name = str(name).strip()
    if not name or len(name) > 64 or name.startswith(".") or _NAME_BAD.search(name):
        raise ValueError(f"not a usable app name: {name!r} (1 to 64 characters, no '/' ':' or leading dot)")
    return name


def default_identifier(name):
    slug = re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-").lower() or "app"
    return f"local.baremacgui.{slug}"


def check_identifier(identifier):
    if not isinstance(identifier, str) or not _IDENTIFIER.match(identifier):
        raise ValueError(f"not a bundle identifier: {identifier!r} (reverse-DNS style, e.g. com.example.notes)")
    return identifier


def info_plist(name, identifier, version="1.0", icon_file=None, background=False, executable="launcher"):
    """The Info.plist contents of the bundle as a dict."""
    info = {
        "CFBundleName": name,
        "CFBundleDisplayName": name,
        "CFBundleIdentifier": identifier,
        "CFBundleExecutable": executable,
        "CFBundlePackageType": "APPL",
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleShortVersionString": str(version),
        "CFBundleVersion": str(version),
        "NSHighResolutionCapable": True,
        "LSMinimumSystemVersion": "10.13",
    }
    if icon_file:
        info["CFBundleIconFile"] = icon_file
    if background:
        info["LSUIElement"] = True
    return info


def launcher_script(python, script, icon_file=None, name=None):
    """The shell script in Contents/MacOS: go to Resources, tell the script its name and icon, start Python."""
    lines = [
        "#!/bin/sh",
        '# Generated by baremacgui. Starts the script with the Python that built this app.',
        'cd "$(dirname "$0")/../Resources" || exit 1',
    ]
    if name:
        lines.append(f"export BAREMACGUI_APP_NAME={shlex.quote(name)}")
    if icon_file:
        lines.append(f'export BAREMACGUI_ICON="$(pwd)/{icon_file}"')
    lines.append(f'exec {shlex.quote(python)} {shlex.quote(script)} "$@"')
    return "\n".join(lines) + "\n"


def _rounded_span(y, top, bottom, left, right, radius):
    """x range [x0, x1) that a rounded rectangle covers on pixel row y, or None."""
    if y < top or y >= bottom:
        return None
    edge = min(y - top + 0.5, bottom - y - 0.5)
    inset = 0.0 if edge >= radius else radius - math.sqrt(max(radius * radius - (radius - edge) ** 2, 0.0))
    return int(round(left + inset)), int(round(right - inset))


def default_icon_png(path, size=1024):
    """Write the plain default icon (a blue rounded square with a small window) as a PNG.

    Pure standard library: shapes are filled row by row, so no imaging library is needed.
    """
    unit = size / 1024.0

    def u(value):
        return int(round(value * unit))

    margin, body = u(100), size - 2 * u(100)
    win_left, win_right = u(250), size - u(250)
    win_top, win_bottom, bar = u(330), u(700), u(430)
    dots = [(u(320), (255, 95, 87)), (u(385), (254, 188, 46)), (u(450), (40, 200, 64))]
    dot_y, dot_r = u(380), u(20)
    lines = [(u(480), u(560)), (u(520), u(640)), (u(560), u(600))]  # (y, right edge) of text-like bars
    rows = []
    for y in range(size):
        row = bytearray(size * 4)

        def paint(span, color, alpha=255):
            if span is not None and span[1] > span[0]:
                row[span[0] * 4:span[1] * 4] = bytes((*color, alpha)) * (span[1] - span[0])

        t = (y - margin) / body
        shade = (int(79 - 48 * t), int(140 - 52 * t), int(255 - 25 * t))  # light blue at the top, deeper below
        paint(_rounded_span(y, margin, margin + body, margin, margin + body, u(185)), shade)
        paint(_rounded_span(y, win_top, win_bottom, win_left, win_right, u(40)), (250, 251, 255))
        if win_top <= y < bar:
            paint(_rounded_span(y, win_top, win_bottom, win_left, win_right, u(40)), (222, 227, 240))
        for cx, color in dots:
            if abs(y - dot_y) < dot_r:
                half = int(math.sqrt(dot_r * dot_r - (y - dot_y) ** 2))
                paint((cx - half, cx + half), color)
        for line_y, right in lines:
            if line_y <= y < line_y + u(22):
                paint(_rounded_span(y, line_y, line_y + u(22), u(300), right, u(11)), (190, 198, 218))
        rows.append(b"\x00" + bytes(row))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(b"".join(rows), 6)) + chunk(b"IEND", b""))
    with open(path, "wb") as handle:
        handle.write(png)


def _icns_from_png(png, target):
    if sys.platform != "darwin":
        raise PlatformError("converting a .png to .icns needs macOS (sips and iconutil); pass an .icns file instead")
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        iconset = os.path.join(tmp, "icon.iconset")
        os.mkdir(iconset)
        for size in (16, 32, 128, 256, 512):
            for scale in (1, 2):
                out = os.path.join(iconset, f"icon_{size}x{size}{'@2x' if scale == 2 else ''}.png")
                subprocess.run(["sips", "-z", str(size * scale), str(size * scale), png, "--out", out],
                               check=True, capture_output=True)
        subprocess.run(["iconutil", "-c", "icns", iconset, "-o", target], check=True, capture_output=True)


def build_app(script, name=None, dest=".", identifier=None, version="1.0", icon=None, background=False,
              include=(), python=None):
    """Create `<dest>/<name>.app` around `script` and return its path.

    icon        an .icns file, or a .png (converted with sips and iconutil on macOS). Without one, a plain
                default icon (a blue square with a small window) is made on macOS.
    background  a menu-bar app without Dock icon (LSUIElement), for use with StatusItem
    include     further files or folders copied next to the script (they are in the working directory)
    python      interpreter to start; default: the one running this code

    An existing bundle of the same name is replaced.
    """
    script = os.path.abspath(str(script))
    if not os.path.isfile(script):
        raise FileNotFoundError(f"script not found: {script}")
    name = check_app_name(name or os.path.splitext(os.path.basename(script))[0].replace("_", " ").strip().title())
    identifier = check_identifier(identifier or default_identifier(name))
    python = os.path.abspath(python or sys.executable)
    if icon is not None and not os.path.isfile(str(icon)):
        raise FileNotFoundError(f"icon not found: {icon}")
    if icon is not None and os.path.splitext(str(icon))[1].lower() not in (".icns", ".png"):
        raise ValueError(f"icon must be an .icns or .png file, got {icon!r}")

    bundle = os.path.join(os.path.abspath(str(dest)), name + ".app")
    if os.path.exists(bundle):
        shutil.rmtree(bundle)
    macos = os.path.join(bundle, "Contents", "MacOS")
    resources = os.path.join(bundle, "Contents", "Resources")
    os.makedirs(macos)
    os.makedirs(resources)

    script_name = os.path.basename(script)
    shutil.copy2(script, os.path.join(resources, script_name))
    for extra in include:
        extra = os.path.abspath(str(extra))
        target = os.path.join(resources, os.path.basename(extra))
        if os.path.isdir(extra):
            shutil.copytree(extra, target)
        elif os.path.isfile(extra):
            shutil.copy2(extra, target)
        else:
            raise FileNotFoundError(f"included path not found: {extra}")

    icon_file = None
    if icon is None and sys.platform == "darwin":  # no icon given: the plain default, never the blank one
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            default_icon_png(os.path.join(tmp, "default.png"))
            icon_file = "AppIcon.icns"
            _icns_from_png(os.path.join(tmp, "default.png"), os.path.join(resources, icon_file))
    elif icon is not None:
        icon_file = "AppIcon.icns"
        if str(icon).lower().endswith(".png"):
            _icns_from_png(os.path.abspath(str(icon)), os.path.join(resources, icon_file))
        else:
            shutil.copy2(str(icon), os.path.join(resources, icon_file))

    with open(os.path.join(bundle, "Contents", "Info.plist"), "wb") as handle:
        plistlib.dump(info_plist(name, identifier, version, icon_file, background), handle)
    launcher = os.path.join(macos, "launcher")
    with open(launcher, "w", encoding="utf-8") as handle:
        handle.write(launcher_script(python, script_name, icon_file, name))
    os.chmod(launcher, os.stat(launcher).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return bundle


def main(argv=None):
    """`python -m baremacgui build script.py [options]`"""
    import argparse

    parser = argparse.ArgumentParser(prog="python -m baremacgui", description="BareMacGUI tools")
    sub = parser.add_subparsers(dest="command", required=True)
    build = sub.add_parser("build", help="wrap a script in a double-clickable .app (unsigned, starts this Python)")
    build.add_argument("script")
    build.add_argument("--name")
    build.add_argument("--dest", default=".")
    build.add_argument("--identifier")
    build.add_argument("--version", default="1.0")
    build.add_argument("--icon")
    build.add_argument("--background", action="store_true", help="menu-bar app without Dock icon")
    build.add_argument("--include", action="append", default=[], help="extra file or folder (repeatable)")
    args = parser.parse_args(argv)
    try:
        path = build_app(args.script, args.name, args.dest, args.identifier, args.version, args.icon,
                         args.background, args.include)
    except (BareMacGUIError, OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(path)
    return 0
