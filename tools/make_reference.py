"""Generate docs/REFERENCE.md from the docstrings and signatures of the public API.

    python tools/make_reference.py            write the file
    python tools/make_reference.py --check    fail if the file is out of date

Runs on any OS: baremacgui imports without AppKit.
"""
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import baremacgui  # noqa: E402
from baremacgui._events import Event, event  # noqa: E402

TARGET = ROOT / "docs" / "REFERENCE.md"

GROUPS = [
    ("App and errors", ["App", "Event", "BareMacGUIError", "PlatformError", "LayoutError"]),
    ("Windows and layout", ["Window", "Sheet", "Popover", "VBox", "HBox", "Spacer", "GroupBox", "TabControl", "Tab",
                            "Sidebar", "Page", "Toolbar", "SplitView"]),
    ("Controls", ["Label", "TextBox", "ComboBox", "DropDown", "Button", "CheckBox", "RadioGroup", "SpinBox", "Slider",
                  "ProgressBar", "Image", "Separator", "SearchField", "SegmentedControl", "DatePicker", "TimePicker", "Switch", "ColorWell",
                  "ListBox", "Table", "IconGrid", "Tree", "Custom"]),
    ("Menus", ["MenuBar", "Menu", "MenuItem", "MenuSeparator", "ContextMenu", "StatusItem"]),
    ("Timer, settings and clipboard", ["Timer", "Settings", "Clipboard"]),
    ("Dialogs", ["show_info", "show_warning", "show_error", "ask_yes_no", "ask_ok_cancel", "input_box", "open_file",
                 "save_file", "choose_folder"]),
]


def first_line(obj):
    doc = inspect.getdoc(obj) or ""
    return doc.split("\n\n")[0].replace("\n", " ").strip()


def signature(obj):
    try:
        text = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return "(...)"
    return text.replace("(self, ", "(").replace("(self)", "()")


def members(cls):
    events, props, methods = [], [], []
    for name in sorted(vars(cls)):
        if name.startswith("_"):
            continue
        value = vars(cls)[name]
        if isinstance(value, event):
            events.append(name)
        elif isinstance(value, property):
            props.append((name, first_line(value.fget), value.fset is not None))
        elif inspect.isfunction(value):
            methods.append((name, signature(value), first_line(value)))
    # inherited public API from base classes defined in this package
    for base in cls.__mro__[1:]:
        if base.__module__.startswith("baremacgui") and base is not object:
            for name in sorted(vars(base)):
                if name.startswith("_") or name in vars(cls):
                    continue
                value = vars(base)[name]
                if isinstance(value, property) and name not in [p[0] for p in props]:
                    props.append((name, first_line(value.fget), value.fset is not None))
                elif isinstance(value, event) and name not in events:
                    events.append(name)
    return sorted(events), sorted(props), methods


def render():
    out = ["# BareMacGUI API reference", "",
           "Generated by `tools/make_reference.py` from the docstrings. Do not edit by hand.", "",
           "Handlers take no arguments. Every event can be given as an `on_*=` option, registered with "
           "`control.on_x(handler)`, used as a decorator, or replaced by assignment.", ""]
    for title, names in GROUPS:
        out += [f"## {title}", ""]
        for name in names:
            obj = getattr(baremacgui, name)
            if inspect.isclass(obj):
                out += [f"### `{name}{signature(obj)}`", ""]
                doc = inspect.getdoc(obj)
                if doc:
                    out += ["```text", doc, "```", ""]
                events, props, methods = members(obj)
                if events:
                    out += ["Events: " + ", ".join(f"`{e}`" for e in events), ""]
                if props:
                    out += ["Properties:", ""]
                    out += [f"- `{n}`{'' if rw else ' (read-only)'}" + (f": {d}" if d else "") for n, d, rw in props]
                    out += [""]
                if methods:
                    out += ["Methods:", ""]
                    out += [f"- `{n}{s}`" + (f": {d}" if d else "") for n, s, d in methods]
                    out += [""]
            else:
                out += [f"### `{name}{signature(obj)}`", "", "```text", inspect.getdoc(obj) or "", "```", ""]
    return "\n".join(out).rstrip() + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            sys.exit("docs/REFERENCE.md is out of date: run python tools/make_reference.py")
        print("reference is up to date")
        return
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
